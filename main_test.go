func TestParseSecretOrURI(t *testing.T) {
	t.Run("secret key", func(t *testing.T) {
		totp, err := parseSecretOrURI("HE4DONRVGQZTEMJQHE4DONRVGQZTEMJQ")
		requireNoError(t, err)
		requireTOTP(t, []byte("98765432109876543210"), sha1Signature, 6, 30, totp)
	})

	t.Run("uri", func(t *testing.T) {
		totp, err := parseSecretOrURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQHE4DONRVGQZTEMJQ&algorithm=SHA512")
		requireNoError(t, err)
		requireTOTP(t, []byte("98765432109876543210"), sha512Signature, 6, 30, totp)
	})
}

func TestParseSecret(t *testing.T) {
	t.Run("no base32 padding needed", func(t *testing.T) {
		// base32 string length is a multiple of 8, so no padding needed
		totp, err := parseSecret("HE4DONRVGQZTEMJQHE4DONRVGQZTEMJQ")
		requireNoError(t, err)
		requireTOTP(t, []byte("98765432109876543210"), sha1Signature, 6, 30, totp)
	})

	t.Run("base32 with padding", func(t *testing.T) {
		// base32 string length isn't a multiple of 8
		totp, err := parseSecret("HE4DONRVGQZTEMJQHE4DONRVGQZTE===")
		requireNoError(t, err)
		requireTOTP(t, []byte("987654321098765432"), sha1Signature, 6, 30, totp)
	})

	t.Run("base32 without padding", func(t *testing.T) {
		// base32 string length isn't a multiple of 8
		totp, err := parseSecret("HE4DONRVGQZTEMJQHE4DONRVGQZTE")
		requireNoError(t, err)
		requireTOTP(t, []byte("987654321098765432"), sha1Signature, 6, 30, totp)
	})

	t.Run("whitespace characters are allowed and ignored", func(t *testing.T) {
		totp, err := parseSecret("HE4D ONRV GQZT EMJQ HE4D ONRV GQZT EMJQ")
		requireNoError(t, err)
		requireTOTP(t, []byte("98765432109876543210"), sha1Signature, 6, 30, totp)
	})
}

func TestParseURI(t *testing.T) {
	t.Run("specify secret parameter only", func(t *testing.T) {
		totp, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ")
		requireNoError(t, err)
		requireTOTP(t, []byte("9876543210"), sha1Signature, 6, 30, totp)
	})

	t.Run("specify all optional parameters", func(t *testing.T) {
		totp, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=8&period=60&algorithm=SHA256&issuer=me")
		requireNoError(t, err)
		requireTOTP(t, []byte("9876543210"), sha256Signature, 8, 60, totp)
	})

	t.Run("empty secret", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=")
		requireError(t, err, "empty secret")
	})

	t.Run("missing secret", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?")
		requireError(t, err, "empty secret")
	})

	t.Run("negative digits", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=-1")
		requireError(t, err, `TOTP: invalid 'digits' parameter: "-1" (requirement: 1 <= digits <= 9)`)
	})

	t.Run("zero digits", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=0")
		requireError(t, err, `TOTP: invalid 'digits' parameter: "0" (requirement: 1 <= digits <= 9)`)
	})

	t.Run("too many digits", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=10")
		requireError(t, err, `TOTP: invalid 'digits' parameter: "10" (requirement: 1 <= digits <= 9)`)
	})

	t.Run("minimum number of digits", func(t *testing.T) {
		totp, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=1")
		requireNoError(t, err)
		requireTOTP(t, []byte("9876543210"), sha1Signature, 1, 30, totp)
	})

	t.Run("maximum number of digits", func(t *testing.T) {
		totp, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&digits=9")
		requireNoError(t, err)
		requireTOTP(t, []byte("9876543210"), sha1Signature, 9, 30, totp)
	})

	t.Run("negative period", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&period=-1")
		requireError(t, err, `TOTP: invalid 'period' parameter: "-1" (requirement: 1 <= period)`)
	})

	t.Run("zero period", func(t *testing.T) {
		_, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&period=0")
		requireError(t, err, `TOTP: invalid 'period' parameter: "0" (requirement: 1 <= period)`)
	})

	t.Run("valid period", func(t *testing.T) {
		totp, err := parseURI("otpauth://totp/LABEL?secret=HE4DONRVGQZTEMJQ&period=1")
		requireNoError(t, err)
		requireTOTP(t, []byte("9876543210"), sha1Signature, 6, 1, totp)
	})
}

func requireTOTP(t *testing.T, secret []byte, algorithmSignature string, digits, period int, totp *TOTP) {
	t.Helper()
	assertEqual(t, string(secret), string(totp.Secret), "wrong secret")
	assertEqual(t, digits, totp.Digits, "wrong digits")
	assertEqual(t, period, totp.Period, "wrong period")
	expectAlgorithm(t, algorithmSignature, totp.Algorithm)
}

const (
	sha1Signature   = "87acec17"
	sha256Signature = "84d89877"
	sha512Signature = "bb96c2fc"
)

// expectAlgorithm checks if a hash constructor function is backed by the expected algorithm.
// Golang doesn't allow us to compare function pointers, so instead, we execute
// the hashing algorithm on a known input, and check its output.
func expectAlgorithm(t *testing.T, expectedSignature string, algorithm func() hash.Hash) {
	t.Helper()

	h := algorithm()
	h.Write([]byte("0123456789"))
	signature := fmt.Sprintf("%x", h.Sum(nil)[:4])

	assertEqual(t, expectedSignature, signature, "wrong algorithm")
}

func requireNoError(t *testing.T, err error) {
	t.Helper()
	if err != nil {
		t.Fatalf("Unexpected error: %v", err)
	}
}

func requireError(t *testing.T, err error, expectedMsg string) {
	t.Helper()
	if err == nil {
		t.Fatal("Expected an error, but got nil")
	}
	if expectedMsg != "" && !strings.Contains(err.Error(), expectedMsg) {
		t.Fatalf("Expected error message to contain %q, but got %q", expectedMsg, err.Error())
	}
}

func assertEqual[T comparable](t *testing.T, expected, actual T, msg string) {
	t.Helper()
	if expected != actual {
		t.Errorf("%s: expected %v, got %v", msg, expected, actual)
	}
}

// ErrWriter returns an [io.Writer] that returns 0, err from all Write calls.
// The implementation follows the pattern laid out by iotest.ErrReader.
func ErrWriter(err error) io.Writer {
	return &errWriter{err: err}
}

type errWriter struct {
	err error
}

func (r *errWriter) Write(p []byte) (int, error) {
	return 0, r.err
}
