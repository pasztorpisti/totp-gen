func TestRun(t *testing.T) {
	testTime := time.Unix(1776982590, 0)
	const uriInput = "\n otpauth://totp/LABEL?secret=M3B3Y43UYO3GY5BAONXW423BEAVSAZWFSF2HIIDUN5VMHILT&digits=6&period=30&algorithm=SHA1&issuer=me \n"
	const secretInput = "\n M3B3 Y43U YO3G Y5BA ONXW 423B EAVS AZWF SF2H IIDU N5VM HILT \n"
	const expectedOutput = "107858\n"

	t.Run("happy path", func(t *testing.T) {
		t.Run("URI input", func(t *testing.T) {
			var output bytes.Buffer
			err := run(bytes.NewBufferString(uriInput), &output, testTime)
			requireNoError(t, err)
			assertEqual(t, expectedOutput, output.String(), "wrong output")
		})

		t.Run("secret input", func(t *testing.T) {
			var output bytes.Buffer
			err := run(bytes.NewBufferString(secretInput), &output, testTime)
			requireNoError(t, err)
			assertEqual(t, expectedOutput, output.String(), "wrong output")
		})
	})

	t.Run("input too large", func(t *testing.T) {
		// Base32 encoded data usually consists of blocks of 8 bytes.
		tooLargeInput := strings.Repeat("MMMMMMMM", maxInputSize/8+1)
		var output bytes.Buffer
		err := run(bytes.NewBufferString(tooLargeInput), &output, testTime)
		requireError(t, err, "input too large")
	})

	t.Run("parse error", func(t *testing.T) {
		t.Run("URI input", func(t *testing.T) {
			invalidURIInput := bytes.NewBufferString("otpauth://totp/LABEL?")
			var output bytes.Buffer
			err := run(invalidURIInput, &output, testTime)
			requireError(t, err, "error parsing input: failed to parse TOTP URI")
		})

		t.Run("secret input", func(t *testing.T) {
			invalidSecretInput := bytes.NewBufferString("0")
			var output bytes.Buffer
			err := run(invalidSecretInput, &output, testTime)
			requireError(t, err, "error parsing input: failed to base32 decode secret")
		})
	})

	t.Run("error reading input", func(t *testing.T) {
		var output bytes.Buffer
		err := run(iotest.ErrReader(errors.New("test error")), &output, testTime)
		requireError(t, err, "error reading input: test error")
	})

	t.Run("error writing output", func(t *testing.T) {
		err := run(bytes.NewBufferString(secretInput), ErrWriter(errors.New("test error")), testTime)
		requireError(t, err, "error writing output: test error")
	})
}

